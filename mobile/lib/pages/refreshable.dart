/// 可以被外部要求重新加载数据的页面。
///
/// 为什么需要这个接口：
///   主界面用 IndexedStack 一次性创建全部页面，所以每个页面的 initState
///   只在 App 启动时执行一次。之后在别的页面改了数据（新增运动员、
///   保存采集记录），当前页面手里的还是旧数据，而且没有刷新途径。
///
///   实现这个接口后，主界面在切 Tab 时调用 reload()，
///   保证看到的数据是最新的。
///
/// 相比直接用 `(state as dynamic).reload()`，用接口的好处是编译期就能
/// 检查出拼写错误与方法签名不符 —— dynamic 调用要到运行时才炸。
abstract interface class Refreshable {
  /// 重新从数据源加载。实现应当幂等，可以安全地重复调用。
  Future<void> reload();
}
