def _set_font(run, size=10.5, bold=False, color=None, zh=FONT_ZH, en=FONT_EN):
    """设字体。中文必须单独设 eastAsia，否则不生效。"""
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = en
    run._element.rPr.rFonts.set(qn("w:eastAsia"), zh)
    if color is not None:
        run.font.color.rgb = color


def h(doc, text, level=1):
    """加标题。同时修正中文字体。"""
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = FONT_EN
        run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT_ZH)
        run.font.color.rgb = ACCENT if level <= 2 else RGBColor(0, 0, 0)
    return p


def para(doc, text, size=10.5, bold=False, italic=False,
         color=None, align=None, space_after=6):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.45
    r = p.add_run(text)
    _set_font(r, size=size, bold=bold, color=color)
    r.font.italic = italic
    return p


def bullet(doc, text, level=0):
    p = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.4
    r = p.add_run(text)
    _set_font(r, size=10.5)
    return p


def numbered(doc, text):
    p = doc.add_paragraph(style="List Number")
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.4
    r = p.add_run(text)
    _set_font(r, size=10.5)
    return p


def quote(doc, text):
    """引用块：用于强调关键判断。"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.8)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.line_spacing = 1.4
    r = p.add_run(text)
    _set_font(r, size=10.5, color=ACCENT)
    return p


def table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER

    hdr = t.rows[0].cells
    for i, text in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        r = p.add_run(text)
        _set_font(r, size=10, bold=True)

    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            r = p.add_run(str(text))
            _set_font(r, size=9.5)

    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t


